#!/usr/bin/env python3
"""Translate a flat ARMv5TE memory image to C++.

usage: translate_image.py <image.bin> <load address> <output directory>

The image must begin with a table of function addresses (bit 0 set = Thumb),
ended by a zero word. Everything reachable from those functions is translated.

Writes into the output directory:
  functions.h   declarations of the translated functions
  code.cpp      the translated functions
  table.cpp     `translated_table`: address (with the Thumb bit) -> function,
                sorted by address and ended by an entry with a null function
  report.txt    what was found, including the gaps the translator knows about
"""
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from dslab import arm_analysis, arm_lift  # noqa: E402


def main(argv: list[str]) -> int:
    if len(argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    image_path, base, out = Path(argv[1]), int(argv[2], 0), Path(argv[3])
    data = image_path.read_bytes()

    entries = []
    for offset in range(0, len(data) - 3, 4):
        (address,) = struct.unpack_from("<I", data, offset)
        if address == 0:
            break
        entries.append((address & ~1, bool(address & 1)))
    else:
        print(f"{image_path}: the function table has no terminating zero", file=sys.stderr)
        return 1
    if not entries:
        print(f"{image_path}: the function table is empty", file=sys.stderr)
        return 1

    image = arm_analysis.Image([arm_analysis.Region("main", base, data)])
    functions = arm_analysis.find_functions(image, entries, scan_pointers=True)
    missing = [e for e in entries if e not in functions]
    if missing:
        print(f"{image_path}: {len(missing)} table entries lie outside the image", file=sys.stderr)
        return 1
    keys = sorted(functions)
    names = {k: f"f_{k[0]:08x}" + ("t" if k[1] else "") for k in keys}

    out.mkdir(parents=True, exist_ok=True)
    declarations = "\n".join(f"void {names[k]}(ds::Cpu& c);" for k in keys)
    (out / "functions.h").write_text(
        '// Generated by translate_image.py.\n#pragma once\n#include "ds_cpu.h"\n' + declarations + "\n",
        encoding="utf-8", newline="\n")

    parts = ["// Generated by translate_image.py.", '#include "ds_cpu.h"', '#include "functions.h"', "",
             "using ds::Cpu;", "using namespace ds;", ""]
    parts += [arm_lift.lift_function(functions[k], names, image) for k in keys]
    (out / "code.cpp").write_text("\n".join(parts), encoding="utf-8", newline="\n")

    table = ["// Generated by translate_image.py.", '#include "functions.h"', '#include "translated_table.h"', "",
             "extern const TranslatedEntry translated_table[] = {"]
    table += [f"    {{0x{k[0] | (1 if k[1] else 0):08x}u, {names[k]}, -1, nullptr, 0u}}," for k in keys]
    table += ["    {0xFFFFFFFFu, nullptr, -1, nullptr, 0u},", "};", ""]
    (out / "table.cpp").write_text("\n".join(table), encoding="utf-8", newline="\n")

    report = [f"table entries: {len(entries)}", f"functions: {len(functions)}",
              f"instructions: {sum(len(f.insns) for f in functions.values())}"]
    for k in keys:
        fn = functions[k]
        if fn.unresolved:
            report.append(f"{names[k]}: computed jumps not followed at "
                          + ", ".join(f"{a:08x}" for a in sorted(fn.unresolved)))
        if fn.bad:
            report.append(f"{names[k]}: cut short: {fn.bad}")
    (out / "report.txt").write_text("\n".join(report) + "\n", encoding="utf-8", newline="\n")
    print("; ".join(report[:3]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
